"""Turn the repaired PDF text (output of extract_pdf.py) into src/lyrics.js.

Usage: python tools/extract_pdf.py mummanikkovai.pdf > fixed.txt
       python tools/build_mummanikkovai.py fixed.txt > src/texts/mummanikkovai.js

Only the ten pāsurams are kept: the recording doesn't recite the taniyan or the
closing "சீரார் தூப்புல் ..." line.

The app estimates start times from the recording's length; Sync mode makes them exact.
"""
import json, re, sys

SKIP = re.compile(r'^(www\.prapatti\.com|\d+|Sunder Kidāmbi|ஶ்ரீ தேசிக ப்ரபந்தம்|மும்மணிக்கோவை)$')
FIXES = {'பாரொன்ற ச்சொன்ன': 'பாரொன்றச் சொன்ன', 'வானேற ப்போமளவும்': 'வானேறப் போமளவும்'}

raw = open(sys.argv[1], encoding='utf-8').read()
for a, b in FIXES.items():
    raw = raw.replace(a, b)
lines = [l.strip() for l in raw.splitlines()]
i = next(k for k, l in enumerate(lines) if l.startswith('சீரொன்று'))
end = next(k for k, l in enumerate(lines) if l.startswith('அடிவரவு'))

out, verse = [], 0
repeated = set()  # pāsurams whose first line starts with ‡ are chanted twice
def flush(buf, verse):
    # a line ends at each ⋆, not where the PDF happens to wrap it
    buf = [re.sub(r'॥.*$', '', l) for l in buf]
    parts = re.split(r'⋆+', ' '.join(buf)) if any('⋆' in l for l in buf) else buf
    for x in parts:
        text = re.sub(r'\s+', ' ', re.sub(r'[⋆‡₃]', '', x)).strip()
        if text:
            out.append({'v': verse, 'text': text})

buf = []
for l in lines[i:end]:
    if not l or SKIP.match(l):
        continue
    m = re.search(r'॥\s*॥\s*(\d+)\s*॥\s*॥', l)
    if l.startswith('‡') and not buf:
        repeated.add(verse)
    buf.append(l)
    if m:  # "॥ n ॥" closes verse n; following lines belong to verse n+1
        flush(buf, verse); buf = []
        verse = int(m.group(1)) + 1
    elif verse == 0 and re.sub(r'[⋆‡₃]', '', l).strip().startswith('வானேற'):
        flush(buf, verse); buf = []
        verse = 1
flush(buf, verse)
out = [o for o in out if o['v'] != 0]  # drop the taniyan

# In the PDF, a pāsuram that starts with ‡ is repeated when chanted, so the recording
# says it twice in a row. Playback follows this order rather than the order of the text.
ORDER = [v for v in sorted({o['v'] for o in out}) for _ in range(2 if v in repeated else 1)]

print('// Generated by tools/build_mummanikkovai.py from prapatti.com\'s Mummanikkovai PDF.')
print('// v = pāsuram number. order: pāsurams in the order they are chanted (those marked ‡ in the PDF are said twice).')
print('window.SLOKAM_TEXTS = window.SLOKAM_TEXTS || {};')
print('window.SLOKAM_TEXTS.mummanikkovai = {')
print('  verseWord: "பாசுரம்", verseCount: %d,' % len({o['v'] for o in out}))
print('  order: %s,' % json.dumps(ORDER))
print('  lines: [')
for o in out:
    print('    ' + json.dumps({'v': o['v'], 'text': o['text']}, ensure_ascii=False) + ',')
print('  ],')
print('};')
